package main

import "fmt"

type Logger interface {
	Log(msg string)
}

type OtherLogger struct{}

func (l *OtherLogger) WriteLog(msg string) {
	fmt.Println("OtherLogger:", msg)
}

type LoggerAdapter struct {
	other *OtherLogger
}

func (a *LoggerAdapter) Log(msg string) {
	a.other.WriteLog(msg)
}

func main() {
	other := &OtherLogger{}
	adapter := &LoggerAdapter{other: other}

	var l Logger = adapter
	l.Log("error logged")
}

